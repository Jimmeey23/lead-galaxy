const assert = require('node:assert/strict');
const ts = require('typescript');
const fs = require('node:fs');
const moduleUnderTest = { exports: {} };
new Function('require', 'module', 'exports', ts.transpileModule(fs.readFileSync('src/lib/metrics.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText)(require, moduleUnderTest, moduleUnderTest.exports);
const { periodMetrics, computeKpis } = moduleUnderTest.exports;
const lead = (id, createdAt, converted = false) => ({ id, createdAt, converted, tried: true, won: converted, retained: false, ltv: 100, purchases: 1, visits: 1, followUpCount: 1, daysToFirstFollowUp: 0, daysToConversion: converted ? 2 : null });
const rows = [lead('a', '2025-12-28'), lead('b', '2026-02-02', true), lead('c', null)];
const monthly = periodMetrics(rows, 'month');
assert.deepEqual(monthly.map(row => row.date), ['2025-12-01', '2026-01-01', '2026-02-01']);
assert.equal(monthly[1].kpis.totalLeads, 0);
assert.equal(monthly[1].kpis.avgTimeToConversion, null);
assert.deepEqual(monthly[2].kpis, computeKpis([rows[1]]));
const weekly = periodMetrics([lead('a', '2025-12-28'), lead('b', '2025-12-29'), lead('c', '2026-01-04')], 'week');
assert.deepEqual(weekly.map(row => row.date), ['2025-12-22', '2025-12-29']);
assert.equal(weekly[1].kpis.totalLeads, 2, 'Monday and Sunday belong to the same week across the year boundary');
assert.equal(periodMetrics([rows[1], rows[1]], 'month')[0].kpis.totalLeads, 1, 'Uses canonical distinct-lead metrics');
assert.deepEqual(periodMetrics([], 'week'), []);
console.log('PASS: calendar gaps, year boundaries, Monday–Sunday weeks, canonical KPI parity, deduplication and empty data.');
